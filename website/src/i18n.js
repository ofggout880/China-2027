export function t(key) {
  const lang = store.getState().language || 'en';
  if (lang === 'fr' && dictionary[key]) {
    return dictionary[key];
  }
  return key;
}

export function updateDOMTranslations() {
  document.title = t("CHINA 2027 · Plan and Track Study Goals · Mock Data Model").replace(' · Mock Data Model', '');
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    el.innerHTML = t(key);
  });
}

export function setupI18n() {
  store.subscribeKey('language', () => {
    updateDOMTranslations();
    if (typeof window !== 'undefined') { window.dispatchEvent(new Event('languagechange')); }
  });
  updateDOMTranslations();
}
